#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
CubeX Modular Installer Assembler & Parity Gate
Assembles standalone POSIX sh / bash / RouterOS .rsc installers from scripts/modules/
and ensures backward-compatible forwarding wrappers stay in sync.
"""
import argparse
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
MODULES_DIR = os.path.join(ROOT, "scripts", "modules")

AUTO_HEADER_SH = "# AUTO-GENERATED by scripts/build_installers.py from scripts/modules/ — DO NOT EDIT MANUALLY.\n"
AUTO_HEADER_RSC = "# AUTO-GENERATED by scripts/build_installers.py from scripts/modules/ros/ — DO NOT EDIT MANUALLY.\n"


def read_mod(rel_path: str) -> str:
    full = os.path.join(MODULES_DIR, rel_path)
    with open(full, "r", encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n")


def extract_common_version() -> str:
    common = read_mod("common.sh")
    m = re.search(r'CUBEX_DEFAULT_TAG="(v?[0-9]+\.[0-9]+(?:\.[0-9]+)?)"', common)
    return m.group(1) if m else "v9.99"


def build_install_sh() -> str:
    ver = extract_common_version()
    common = read_mod("common.sh")
    fnos = read_mod("platform_fnos.sh")
    ow = read_mod("platform_openwrt_docker.sh")
    linux = read_mod("platform_linux.sh")

    body = f"""#!/bin/sh
{AUTO_HEADER_SH}# ═════════════════════════════════════════════════════════════════════════════
# 🌌 CubeX Universal Deployer · 次世代双擎高可用旁路网关一键极速安装程序
# Target Version: {ver}
# Supported Hosts: 爱快 iKuai (KVM/Docker/主路由联动), 飞牛 fnOS, RouterOS, PVE, OpenWrt, Linux
# ═════════════════════════════════════════════════════════════════════════════
set -e

{common}
{fnos}
{ow}
{linux}

# ─────────────────────────────────────────────────────────────────────────────
# 统一命令行入口与多平台分发
# ─────────────────────────────────────────────────────────────────────────────
AUTO_CONFIRM=0
DEPLOY_MODE=""
PLATFORM_OVERRIDE="auto"
CUSTOM_DIR=""
CUSTOM_VER=""

for _arg in "$@"; do
    case "$_arg" in
        -y|--yes|--silent)
            AUTO_CONFIRM=1
            ;;
        --docker)
            DEPLOY_MODE="docker"
            ;;
        --native)
            DEPLOY_MODE="native"
            ;;
        --platform=*)
            PLATFORM_OVERRIDE="${{_arg#*=}}"
            ;;
        --dir=*)
            CUSTOM_DIR="${{_arg#*=}}"
            ;;
        --version=*|-v=*)
            CUSTOM_VER="${{_arg#*=}}"
            ;;
    esac
done

[ -z "$CUSTOM_VER" ] && CUSTOM_VER="${{CUBEX_VERSION:-}}"
REL_TAG="{ver}"

case "$PLATFORM_OVERRIDE" in
    fnos)
        run_platform_fnos
        ;;
    openwrt-docker|openwrt)
        run_platform_openwrt_docker
        ;;
    auto|linux|pve|"")
        run_platform_linux
        ;;
    *)
        msg "${{RED}}❌ 未知平台参数: $PLATFORM_OVERRIDE (支持 auto/linux/fnos/openwrt-docker)${{NC}}"
        exit 1
        ;;
esac
"""
    return body


def build_pve_lxc_sh() -> str:
    ver = extract_common_version()
    common = read_mod("common.sh")
    pve_host = read_mod("platform_pve_host.sh")
    body = f"""#!/usr/bin/env bash
{AUTO_HEADER_SH}# ==============================================================================
# 🌌 CubeX - PVE LXC (CT) 容器极致轻量一键全自动极速安装程序 (实测强化版)
# Target Version: {ver}
# 适用环境: Proxmox VE 7.x / 8.x / 9.x (x86_64 / arm64)
# ==============================================================================
set -e

{common}
REL_TAG="{ver}"
{pve_host}
"""
    return body


def build_forwarding_wrapper(name: str, desc: str, target_flag: str, local_sibling: str = "../install.sh") -> str:
    ver = extract_common_version()
    return f"""#!/bin/sh
{AUTO_HEADER_SH}# ═════════════════════════════════════════════════════════════════════════════
# 🌌 CubeX 向后兼容转发入口 ({name})
# {desc}
# Target Version: {ver}
# ═════════════════════════════════════════════════════════════════════════════
set -e

_WRAP_DIR=$(cd "$(dirname "$0")" && pwd)
if [ -f "${{_WRAP_DIR}}/{local_sibling}" ]; then
    exec sh "${{_WRAP_DIR}}/{local_sibling}" {target_flag} "$@"
fi
if [ -f "${{_WRAP_DIR}}/install.sh" ]; then
    exec sh "${{_WRAP_DIR}}/install.sh" {target_flag} "$@"
fi
if [ -s "/tmp/cubex_install.sh" ] && head -n 1 /tmp/cubex_install.sh 2>/dev/null | grep -q "^#!/bin/sh"; then
    exec sh /tmp/cubex_install.sh {target_flag} "$@"
fi

_TMP_INST="/tmp/cubex_install.sh"
_DL_INST="/tmp/cubex_install.sh.dl.$$"
for _MIRROR in "https://ghfast.top" "https://ghproxy.net" "https://gh-proxy.com" "https://gh.ddlc.top" ""; do
    _URL="${{_MIRROR}}/https://raw.githubusercontent.com/zyeyefyass/CubeX/main/install.sh"
    [ -z "$_MIRROR" ] && _URL="https://raw.githubusercontent.com/zyeyefyass/CubeX/main/install.sh"
    rm -f "$_DL_INST"
    if command -v curl >/dev/null 2>&1; then
        curl -4 -fsSL --connect-timeout 5 -m 20 -o "$_DL_INST" "$_URL" 2>/dev/null || true
    elif command -v wget >/dev/null 2>&1; then
        wget -q -T 20 -O "$_DL_INST" "$_URL" 2>/dev/null || true
    fi
    if [ -s "$_DL_INST" ] && head -n 1 "$_DL_INST" 2>/dev/null | grep -q "^#!/bin/sh"; then
        mv -f "$_DL_INST" "$_TMP_INST"
        chmod +x "$_TMP_INST"
        exec sh "$_TMP_INST" {target_flag} "$@"
    fi
    rm -f "$_DL_INST"
done

echo "❌ 无法拉取 CubeX 主安装脚本 install.sh，请检查网络连接！"
exit 1
"""


def build_rsc(template_rel: str) -> str:
    common_rsc = read_mod("ros/common.rsc").rstrip("\n")
    tpl = read_mod(template_rel)
    rendered = tpl.replace("@INCLUDE_ROS_COMMON@", common_rsc)
    lines = rendered.splitlines(keepends=True)
    if lines and lines[0].startswith("#"):
        return lines[0] + AUTO_HEADER_RSC + "".join(lines[1:])
    return AUTO_HEADER_RSC + rendered


def expected_outputs() -> dict[str, str]:
    install_sh = build_install_sh()
    pve_sh = build_pve_lxc_sh()
    ros_container = build_rsc("ros/container.rsc")
    ros_bypass = build_rsc("ros/bypass.rsc")
    ow_setup = build_forwarding_wrapper(
        "scripts/openwrt/setup-openwrt.sh",
        "适用底座: OpenWrt / iStoreOS Docker Macvlan (自动转发至 install.sh --platform=openwrt-docker)",
        "--platform=openwrt-docker",
        "../install.sh",
    )
    ow_docker = build_forwarding_wrapper(
        "scripts/install_openwrt_docker.sh",
        "适用底座: OpenWrt / iStoreOS Docker 一键兼容入口",
        "--platform=openwrt-docker",
        "./install.sh",
    )
    fnos_wrap = build_forwarding_wrapper(
        "scripts/fnos/install-fnos.sh",
        "适用底座: 飞牛 fnOS Docker 专属一键兼容入口",
        "--platform=fnos",
        "../install.sh",
    )
    return {
        "scripts/install.sh": install_sh,
        "install.sh": install_sh,
        "scripts/install_pve_lxc.sh": pve_sh,
        "install_pve_lxc.sh": pve_sh,
        "scripts/openwrt/setup-openwrt.sh": ow_setup,
        "scripts/install_openwrt_docker.sh": ow_docker,
        "scripts/fnos/install-fnos.sh": fnos_wrap,
        "scripts/install_ros_container.rsc": ros_container,
        "install_ros_container.rsc": ros_container,
        "scripts/ros/setup-routeros-v7.rsc": ros_bypass,
    }


def main():
    parser = argparse.ArgumentParser(description="Build modular CubeX installers")
    parser.add_argument("--check", action="store_true", help="Verify generated outputs match files on disk")
    args = parser.parse_args()

    outputs = expected_outputs()
    if args.check:
        mismatches = []
        for rel, content in outputs.items():
            full = os.path.join(ROOT, rel)
            if not os.path.exists(full):
                mismatches.append(f"{rel} (missing)")
                continue
            with open(full, "rb") as f:
                disk = f.read().decode("utf-8", errors="replace").replace("\r\n", "\n")
            if disk != content:
                mismatches.append(rel)
        if mismatches:
            print(f"❌ Installer parity check FAILED! Out-of-sync generated files: {mismatches}")
            sys.exit(1)
        print(f"✓ Modular installer parity check PASSED ({len(outputs)} files in sync with scripts/modules/)")
        return

    for rel, content in outputs.items():
        full = os.path.join(ROOT, rel)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "wb") as f:
            f.write(content.encode("utf-8"))
        if rel.endswith(".sh"):
            try:
                os.chmod(full, 0o755)
            except Exception:
                pass
        print(f"✓ Built {rel} ({len(content.encode('utf-8'))} B)")


if __name__ == "__main__":
    main()
